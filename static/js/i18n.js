function getLang() {
  return localStorage.getItem('preferred_lang') || 'zh';
}

function setLang(code) {
  localStorage.setItem('preferred_lang', code);
}

function t(key) {
  const lang = getLang();
  const dict = T[lang] || T['en'];
  return dict[key] || T['en'][key] || key;
}

function bilingual(key) {
  const lang = getLang();
  const primary = (T[lang] || T['en'])[key] || key;
  const english = T['en'][key] || key;
  if (lang === 'en' || primary === english) return primary;
  return `${primary} / ${english}`;
}
